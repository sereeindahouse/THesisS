def main():
    source, target = Path(sys.argv[1]), Path(sys.argv[2])
    content = json.loads(source.read_text(encoding='utf-8'))
    seen = set()
    for faq in content['faqs']:
        key = faq['faq_id']
        if key in ANSWERS:
            old = faq['answer']
            faq['answer'] = ANSWERS[key]
            note = (faq.get('notes') or '').strip()
            faq['notes'] = (note + ' ' if note else '') + 'v2-ийн хариулт (2026-11-23-нд энгийн үгээр солив): ' + old
            seen.add(key)
        if key in EXPIRED:
            faq['approval_status'] = 'expired'
            faq['notes'] = ((faq.get('notes') or '').strip() + ' ' + EXPIRED[key]).strip()
            seen.add(key)
    missing = sorted((set(ANSWERS) | set(EXPIRED)) - seen)
    if missing:
        raise SystemExit('Unknown FAQ IDs: ' + ', '.join(missing))
    errors = validate_content(content)
    if errors:
        raise SystemExit('Invalid content:\n' + '\n'.join(errors))
    target.write_text(json.dumps(content, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'{target}: {len(seen)} FAQ records changed, validation OK')


if __name__ == '__main__':
    main()
